use crate::model::{Layout, quote};
use anyhow::{Context, Result};
use std::{
    fs,
    io::Write,
    path::{Path, PathBuf},
};
use tempfile::NamedTempFile;

pub fn directory() -> Result<PathBuf> {
    if let Some(path) = std::env::var_os("XDG_CONFIG_HOME").filter(|s| !s.is_empty()) {
        let path = PathBuf::from(path);
        anyhow::ensure!(path.is_absolute(), "XDG_CONFIG_HOME must be absolute");
        Ok(path.join("layman"))
    } else {
        Ok(
            PathBuf::from(std::env::var_os("HOME").context("HOME is unset")?)
                .join(".config/layman"),
        )
    }
}
pub fn load() -> Result<Option<Layout>> {
    load_at(&directory()?)
}
pub fn load_at(dir: &Path) -> Result<Option<Layout>> {
    match fs::read(dir.join("layout.json")) {
        Ok(data) => {
            let l: Layout = serde_json::from_slice(&data).context("Cannot read saved layout")?;
            l.validate()?;
            Ok(Some(l))
        }
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(e) => Err(e.into()),
    }
}
pub fn config(layout: &Layout, executable: &Path) -> Result<String> {
    let mut text = String::from(
        "# Generated by Layman. Edit layouts in the app.\n# Include this AFTER other output/workspace rules in your Sway config.\n",
    );
    // Disable commands run only through --restore, after verifying an enabled saved
    // screen is actually connected. This keeps an undocked laptop usable on reload.
    for command in layout
        .output_commands(true)?
        .into_iter()
        .filter(|c| !c.ends_with(" disable"))
    {
        text.push_str(&command);
        text.push('\n');
    }
    for w in &layout.workspaces {
        let o = layout
            .outputs
            .iter()
            .find(|o| o.name == w.output)
            .context("Missing output")?;
        text.push_str(&format!(
            "workspace {} output {}\n",
            quote(&w.name)?,
            quote(&o.identity())?
        ));
    }
    text.push_str(&format!(
        "exec_always {} --restore\n",
        quote(executable.to_str().context("Non-UTF-8 executable path")?)?
    ));
    Ok(text)
}
fn stage(dir: &Path, data: &[u8]) -> Result<NamedTempFile> {
    let mut f = NamedTempFile::new_in(dir)?;
    f.write_all(data)?;
    f.as_file().sync_all()?;
    Ok(f)
}
pub fn save_at(dir: &Path, layout: &Layout, executable: &Path) -> Result<()> {
    layout.validate()?;
    fs::create_dir_all(dir)?;
    let config = config(layout, executable)?;
    let json = serde_json::to_vec_pretty(layout)?;
    let staged_config = stage(dir, config.as_bytes())?;
    let staged_json = stage(dir, &json)?;
    let config_path = dir.join("sway.conf");
    let previous_config = match fs::read(&config_path) {
        Ok(bytes) => Some(bytes),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => None,
        Err(e) => return Err(e.into()),
    };
    staged_config.persist(&config_path)?;
    if let Err(e) = staged_json.persist(dir.join("layout.json")) {
        // Don't leave a new include paired with an old restore layout.
        match previous_config {
            Some(data) => {
                stage(dir, &data)?.persist(config_path)?;
            }
            None => {
                fs::remove_file(config_path)?;
            }
        }
        return Err(e.into());
    }
    fs::File::open(dir)?.sync_all()?;
    Ok(())
}
pub fn save(layout: &Layout) -> Result<()> {
    save_at(&directory()?, layout, &std::env::current_exe()?)
}
pub fn include_line() -> Result<String> {
    Ok(format!(
        "include {}",
        quote(
            directory()?
                .join("sway.conf")
                .to_str()
                .context("Non-UTF-8 config path")?
        )?
    ))
}

/// OS-released lock: stale files are harmless after a process crash.
pub fn mutation_lock() -> Result<Option<fs::File>> {
    let dir = directory()?;
    fs::create_dir_all(&dir)?;
    let file = fs::OpenOptions::new()
        .read(true)
        .write(true)
        .create(true)
        .truncate(false)
        .open(dir.join("mutation.lock"))?;
    match file.try_lock() {
        Ok(()) => Ok(Some(file)),
        Err(fs::TryLockError::WouldBlock) => Ok(None),
        Err(fs::TryLockError::Error(e)) => Err(e.into()),
    }
}
